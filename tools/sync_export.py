#!/usr/bin/env python3
"""Re-inline resume-export.js, voice-adapter.js and pdf-text.js into index.html.

resume-export.js is the single source of truth for PDF/DOCX/TXT output.
Run this after editing it:   python3 tools/sync_export.py
Then re-run the tests:       bash tests/run-all.sh
"""
import pathlib, re, sys

root = pathlib.Path(__file__).resolve().parent.parent
engine = (root / 'resume-export.js').read_text()
voice = (root / 'voice-adapter.js').read_text()
pdftext = (root / 'pdf-text.js').read_text()

def sync_block(h, start_marker, end_marker, body):
    start = h.index(start_marker)
    end = h.index(end_marker, start) + len(end_marker)
    return h[:start] + start_marker + '\n' + body + '\n' + end_marker + h[end:]

def sync_index():
    p = root / 'index.html'
    h = p.read_text()
    h = sync_block(h,
                   '/* ===== VoiceAdapter (inlined from voice-adapter.js) ===== */',
                   '/* ===== end VoiceAdapter ===== */', voice)
    h = sync_block(h,
                   '/* ===== PdfText (inlined from pdf-text.js) ===== */',
                   '/* ===== end PdfText ===== */', pdftext)
    h = sync_block(h,
                   '/* ===== ResumeExport (inlined from resume-export.js) ===== */',
                   '/* ===== end ResumeExport ===== */', engine)
    p.write_text(h)
    return len(h)

def sync_desktop():
    p = root / 'desktop.html'
    h = p.read_text()
    start = h.index('<script id="engine">')
    end = h.index('</script>', start) + len('</script>')
    block = ('<script id="engine">\n/* ===== ResumeExport engine (generated by '
             'tools/sync_export.py — edit resume-export.js instead) ===== */\n'
             + engine + '\n</script>')
    h = h[:start] + block + h[end:]
    p.write_text(h)
    return len(h)

a = sync_index(); b = sync_desktop()
print(f'index.html  {a:,} bytes\n desktop.html {b:,} bytes\nengine synced from resume-export.js')
